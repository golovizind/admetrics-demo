#!/usr/bin/env bash
# Admetrics в одном терминале: бот, панель, туннель.
# Ctrl+C останавливает всё сразу.
#
# Почему так, а не три вкладки: части системы связаны. Панель без туннеля
# недоступна из Telegram, туннель без панели отдаёт 502, а бот рисует кнопку
# по файлу .webapp_url, который пишет туннель. Запуск вместе убирает
# состояния «поднял половину и забыл».

set -u
cd "$(dirname "$0")"

PORT="${PORT:-8080}"
PY=.venv/bin/python

# Старые копии убиваем в первую очередь. Два бота на одном токене дерутся
# за getUpdates, и отвечает тот, кто успел первым — то есть иногда старый код.
for name in bot.py webapp.py tunnel.py tg_worker.py; do pkill -f "$name" 2>/dev/null; done
sleep 2

set -a; . ./.env; set +a

# Убить всю группу процессов, а не только последний.
trap 'kill 0' EXIT

# Панель открывается в обычном браузере по http://127.0.0.1:$PORT — без
# Telegram, без туннеля и без сертификата. Флаг даёт права админа запросам,
# пришедшим на loopback-адрес.
#
# С туннелем его включать НЕЛЬЗЯ, и это не перестраховка: туннель
# подключается к 127.0.0.1, так что по адресу соединения он неотличим от
# браузера на этой машине. Права админа получил бы каждый, кто знает
# публичный адрес.
if [[ "${TUNNEL:-0}" == "1" ]]; then
  export ADMETRICS_LOCAL_ADMIN=0
  echo "[панель]  туннель включён → локальный админ выключен, вход только из Telegram"
else
  export ADMETRICS_LOCAL_ADMIN=1
fi

# -u обязателен: через пайп Python буферизует вывод блоками, и логи
# появлялись бы пачками через минуты вместо реального времени.
"$PY" -u webapp.py --port "$PORT" 2>&1 | sed 's/^/[панель]  /' &
"$PY" -u tg_worker.py 2>&1 | sed 's/^/[tg]      /' &

# Туннель по умолчанию НЕ поднимается: бесплатный выдаёт новый адрес на
# каждый подъём, и кнопка в боте живёт до первого обрыва. Нужен — TUNNEL=1.
if [[ "${TUNNEL:-0}" == "1" ]]; then
  sleep 3
  "$PY" -u tunnel.py --port "$PORT" 2>&1 | sed 's/^/[туннель] /' &
else
  echo "[панель]  открывайте http://127.0.0.1:$PORT — туннель выключен (TUNNEL=1 включит)"
fi

# Бот под присмотром: любое падение — подъём через 5 секунд.
# tunnel.py умеет это сам, панель переживает ошибки запросов.
while :; do
  "$PY" -u bot.py 2>&1 | sed 's/^/[бот]     /'
  echo "[бот]     упал, поднимаю через 5 с"
  sleep 5
done
